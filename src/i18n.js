/**
 * Format a measured duration honestly (audit 9): ONE fixed unit
 * everywhere — milliseconds. The old rule switched units at the
 * 1 s threshold, so the same kind of check printed "2.7 dtk" one
 * time and "320.7 md" the next, and seconds rounded every
 * sub-second check to "0.0". A real measured wait is always shown
 * in ms (locale-formatted, so 6500 ms reads "6.500,0 md" in ID);
 * values under 1 ms get two decimals so they never print as "0.0".
 * Never padded — the number is the real measured wait.
 * `forceUnit` is kept only so older callers do not break; it is
 * ignored — the unit is always milliseconds.
 */
export function formatElapsed(sec, lang, forceUnit) {
  void forceUnit;
  const s = Number(sec);
  if (!Number.isFinite(s) || s < 0) return "—";
  const ms = s * 1000;
  const locale = lang === "id" ? "id-ID" : "en-US";
  const digits = ms < 1 ? 2 : 1;
  return `${ms.toLocaleString(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits })} ${lang === "id" ? "md" : "ms"}`;
}
