function fmt(str, vars) {
  if (!vars) return str;
  return String(str).replaceAll(/\{(\w+)\}/g, (_, k) =>
    vars[k] != null ? String(vars[k]) : `{${k}}`,
  );
}

/** Translate a UI key; falls back to English, then to the key itself. */
export function t(key, lang, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  const str = table[key] ?? STRINGS.en[key] ?? key;
  return fmt(str, vars);
}

/** Translate a demo-mode summary (status: scam | suspicious | safe). */
export function demoSummary(status, lang) {
  const table = DEMO[lang] || DEMO.en;
  return table.summaries[status] || DEMO.en.summaries[status] || "";
}

/** Translate one demo-mode red flag (English source text in, localized out). */
export function demoFlag(flagEn, lang) {
  if (lang === "en") return flagEn;
  const table = DEMO[lang] || DEMO.en;
  return table.flags[flagEn] || flagEn;
}
