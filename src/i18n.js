// TipuCek — interface translations (8 languages) + automatic detection.
//
// The UI language is picked automatically: ?lang= URL parameter first,
// then the saved choice (localStorage), then the browser language
// (navigator.language). Anything else falls back to English.
// The AI verdict (summary + red flags) is also returned in the UI
// language: the check prompt asks the model for it, and the local demo
// heuristic translates its fixed strings through the DEMO table below.

export const LANGUAGES = [
  { code: "en", name: "English", aiName: "English" },
  { code: "id", name: "Bahasa Indonesia", aiName: "Indonesian" },
  { code: "es", name: "Español", aiName: "Spanish" },
  { code: "fr", name: "Français", aiName: "French" },
  { code: "de", name: "Deutsch", aiName: "German" },
  { code: "pt", name: "Português", aiName: "Portuguese" },
  { code: "ja", name: "日本語", aiName: "Japanese" },
  { code: "zh", name: "中文", aiName: "Chinese" },
];

const LS_LANG_KEY = "pesanaman_lang";

export function isSupported(code) {
  return LANGUAGES.some((l) => l.code === code);
}

export function languageName(code) {
  return (LANGUAGES.find((l) => l.code === code) || LANGUAGES[0]).aiName;
}

export function detectLanguage() {
  try {
    const q = new URLSearchParams(window.location.search).get("lang");
    if (q && isSupported(q)) return q;
    const saved = localStorage.getItem(LS_LANG_KEY);
    if (saved && isSupported(saved)) return saved;
  } catch {
    /* storage / URL unavailable — fall through to browser language */
  }
  const nav = (navigator.language || "en").toLowerCase();
  const base = nav.split("-")[0];
  if (isSupported(base)) return base;
  return "en";
}

export function saveLanguage(code) {
  try {
    localStorage.setItem(LS_LANG_KEY, code);
  } catch {
    /* private mode — the choice just won't persist */
  }
}

